"""Pydantic schemas for tasks, plans, sources, evidence, citations, and reports."""
from datetime import datetime
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, HttpUrl


class TaskStatus(str, Enum):
    """Execution states for research tasks in LangGraph."""
    CREATED = "CREATED"
    PLANNING = "PLANNING"
    COLLECTING_EVIDENCE = "COLLECTING_EVIDENCE"
    VALIDATING_SOURCES = "VALIDATING_SOURCES"
    AWAITING_APPROVAL = "AWAITING_APPROVAL"
    GENERATING_REPORT = "GENERATING_REPORT"
    VERIFYING_REPORT = "VERIFYING_REPORT"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    CANCELED = "CANCELED"


class TaskCreate(BaseModel):
    """Task submission payload."""
    topic: str = Field(..., min_length=3, max_length=500, description="Research topic or question")
    constraints: List[str] = Field(default_factory=list, description="Target constraints, e.g. dates, domains")
    max_tool_calls: Optional[int] = Field(default=15, ge=1, le=50, description="Maximum allowed tool calls")
    require_human_approval: bool = Field(default=False, description="Pause for manual review before report generation")


class TaskResponse(BaseModel):
    """Task representation returned by API."""
    id: str
    user_id: str
    topic: str
    status: TaskStatus
    created_at: datetime
    updated_at: datetime
    completed_at: Optional[datetime] = None
    max_tool_calls: int
    current_tool_calls: int
    requires_approval: bool
    approval_reason: Optional[str] = None
    error_message: Optional[str] = None

    class Config:
        from_attributes = True


class ApprovalRequest(BaseModel):
    """Payload to approve or resume a paused task."""
    approved: bool = Field(..., description="True to proceed, False to reject/cancel")
    feedback: Optional[str] = Field(default=None, description="Optional guidance or refinement instruction")


class ResearchPlan(BaseModel):
    """Structured research plan generated by the Planner node."""
    objectives: List[str] = Field(..., min_items=1, description="Primary research objectives")
    subquestions: List[str] = Field(..., min_items=2, description="Decomposed subquestions")
    search_queries: List[str] = Field(..., min_items=2, description="Target search queries")
    information_requirements: List[str] = Field(default_factory=list, description="Authoritative data needed")
    expected_sections: List[str] = Field(default_factory=list, description="Planned report section headers")


class SourceMetadata(BaseModel):
    """Metadata for retrieved and verified web sources."""
    source_id: str = Field(..., description="Unique source identifier, e.g. src-1")
    url: str = Field(..., description="Verified canonical source URL")
    title: str = Field(..., description="Extracted page title")
    domain: str = Field(..., description="Extracted domain hostname")
    retrieved_at: datetime = Field(default_factory=datetime.utcnow)
    status_code: int = Field(default=200)
    is_trusted: bool = Field(default=True)


class EvidenceChunk(BaseModel):
    """Extracted text chunk linked to a source ID."""
    chunk_id: str
    source_id: str
    url: str
    text: str
    char_count: int
    question_addressed: Optional[str] = None


class CitationStatus(str, Enum):
    """Verification outcome of a report citation."""
    VERIFIED = "VERIFIED"
    UNSUPPORTED = "UNSUPPORTED"
    HALLUCINATED_ID = "HALLUCINATED_ID"
    CONTRADICTED = "CONTRADICTED"


class CitationVerificationResult(BaseModel):
    """Individual citation check result."""
    citation_marker: str = Field(..., description="e.g. [^src-1]")
    source_id: str
    url: Optional[str] = None
    claimed_statement: str
    supporting_excerpt: Optional[str] = None
    status: CitationStatus
    confidence: float = Field(ge=0.0, le=1.0)
    note: Optional[str] = None


class ReportResponse(BaseModel):
    """Completed research report with verified citations."""
    task_id: str
    topic: str
    content_markdown: str
    sources: List[SourceMetadata]
    citation_audit: List[CitationVerificationResult]
    total_sources: int
    total_citations: int
    verified_citations: int
    grounding_score: float = Field(ge=0.0, le=1.0)
